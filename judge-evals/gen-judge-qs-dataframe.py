# print(df['SOURCE'].value_counts())
# df[df['SOURCE'].isna() | (df['SOURCE'] == "")].to_csv('check-these.csv')
for idx, row in df.iterrows():
    try:
        if row['SOURCE'] in ['harmful', 'harmful-long', 'harmful-single']:
            df.at[idx, 'judge_prompt'] = build_harmful_judge_prompt(
                row['post-intervention-response'],
                row['original-response'],
                row['query']
            )
        elif row['SOURCE'] == 'hate':
            df.at[idx, 'judge_prompt'] = build_hate_love_judge_prompt(
                row['post-intervention-response'],
                row['original-response'],
                row['query']
            )
        elif row['SOURCE'] in ['verse', 'verse-long', 'verse-single']:
            df.at[idx, 'judge_prompt'] = build_verse_judge_prompt(
                row['post-intervention-response'],
                row['query']
            )
        elif row['SOURCE'] in ['anti-long', 'anti-single']:
            df.at[idx, 'judge_prompt'] = build_refusal_judge_prompt(
                row['post-intervention-response'],
                row['original-response'],
                row['query']
            )
        elif row['SOURCE'] in ['paragraph-long', 'paragraph-single']:
            df.at[idx, 'judge_prompt'] = build_para_judge_prompt(
                row['post-intervention-response'],
                row['original-response'],
                row['query']
            )
    except AssertionError as e:
        print(f"Error on row")
# print(df[df['judge_prompt'].isna()]['SOURCE'].value_counts())
if df.isna().any().any():
    bad_rows = df[df.isna().any(axis=1)]

    lines = []
    for idx, row in bad_rows.iterrows():
        nan_cols = row.index[row.isna()].tolist()
        lines.append(f"[row {idx}] NaN cols={nan_cols} | query={row['data_path_query']!r}")

    raise ValueError("NaNs detected:\n" + "\n".join(lines))



